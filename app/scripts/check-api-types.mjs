// Falla si `src/shared/api/schema.d.ts` no coincide con lo que generaría `api/openapi.json`.
// Uso: `npm run gen:api:check`. Para actualizar el archivo: `npm run gen:api`.
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const specUrl = new URL('../../api/openapi.json', import.meta.url);
const schemaUrl = new URL('../src/shared/api/schema.d.ts', import.meta.url);
const schemaPath = fileURLToPath(schemaUrl);

const normalizeEol = (text) => text.replace(/\r\n/g, '\n');

const ast = await openapiTS(specUrl);
const options = (await prettier.resolveConfig(schemaPath)) ?? {};
// La CLI antepone esta cabecera; la API de Node no.
const header =
  '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
const expected = await prettier.format(header + astToString(ast), {
  ...options,
  filepath: schemaPath,
});
const current = await readFile(schemaUrl, 'utf8').catch(() => '');

if (normalizeEol(current) !== normalizeEol(expected)) {
  console.error(
    'src/shared/api/schema.d.ts está desactualizado respecto a api/openapi.json. ' +
      'Ejecuta `npm run gen:api` y confirma el cambio.',
  );
  process.exit(1);
}

console.log('src/shared/api/schema.d.ts está al día con api/openapi.json.');
